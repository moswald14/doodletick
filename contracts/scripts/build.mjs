import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import solc from 'solc';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Use build.mjs [--check].');
if (!solc.version().startsWith('0.8.38+')) throw new Error('Install pinned dependencies with npm ci.');
if (JSON.parse(await readFile(path.join(root, 'node_modules/@openzeppelin/contracts/package.json'), 'utf8')).version !== '5.6.1') throw new Error('Install pinned OpenZeppelin 5.6.1.');
const sources = {};
async function collect(name) {
  if (sources[name]) return;
  if (name !== 'src/DoodleGarden.sol' && !/^@openzeppelin\/contracts\/[a-zA-Z0-9/._-]+\.sol$/.test(name)) throw new Error('Unexpected source import.');
  const file = name.startsWith('@') ? path.join(root, 'node_modules', name) : path.join(root, name);
  const content = (await readFile(file, 'utf8')).replace(/\r\n/g, '\n');
  sources[name] = { content };
  for (const match of content.matchAll(/import\s+(?:[^;]*?\s+from\s+)?["']([^"']+)["']\s*;/g)) {
    const imported = match[1].startsWith('.') ? path.posix.normalize(path.posix.join(path.posix.dirname(name), match[1])) : match[1];
    await collect(imported);
  }
}
await collect('src/DoodleGarden.sol');
const settings = { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris', metadata: { bytecodeHash: 'none' },
  outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.methodIdentifiers', 'storageLayout'] } } };
const input = { language: 'Solidity', sources: Object.fromEntries(Object.entries(sources).sort(([a], [b]) => a.localeCompare(b, 'en'))), settings };
const output = JSON.parse(solc.compile(JSON.stringify(input)));
for (const error of output.errors ?? []) {
  if (error.severity === 'error') throw new Error(error.formattedMessage);
  console.error(error.formattedMessage);
}
const compiled = output.contracts['src/DoodleGarden.sol'].DoodleGarden;
const artifact = {
  contract: 'DoodleGarden', version: 1, compiler: solc.version(), openZeppelin: '5.6.1', evmVersion: settings.evmVersion,
  sourceSha256: createHash('sha256').update(JSON.stringify(input)).digest('hex'),
  abi: compiled.abi, selectors: compiled.evm.methodIdentifiers,
  bytecode: '0x' + compiled.evm.bytecode.object, deployedBytecode: '0x' + compiled.evm.deployedBytecode.object,
};
const files = new Map([
  ['artifacts/compiler-input.json', JSON.stringify(input, null, 2) + '\n'],
  ['artifacts/DoodleGarden.json', JSON.stringify({ ...artifact, storageLayout: compiled.storageLayout }, null, 2) + '\n'],
  ['../keeper/public/public-chain-artifact.mjs', '// Generated by contracts/scripts/build.mjs; do not edit.\n// DoodleGarden: GPL-3.0-only. Includes OpenZeppelin ERC20: MIT; see contracts/OPENZEPPELIN-LICENSE.txt.\nexport const GARDEN_ARTIFACT = Object.freeze(' + JSON.stringify(artifact) + ');\n'],
]);
for (const [name, content] of files) {
  const file = path.resolve(root, name);
  if (check) {
    if (await readFile(file, 'utf8') !== content) throw new Error(`Rebuild required: ${name}`);
  } else {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, content, 'utf8');
  }
}
console.log(`${check ? 'Verified' : 'Built'} DoodleGarden with ${solc.version()}; ${artifact.deployedBytecode.length / 2 - 1} runtime bytes.`);
