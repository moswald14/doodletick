// Read-only end cards. These outputs never become input to the story machine.
(function(root){
  'use strict';
  const STAGES=new Set(['POEM GEN','TELEPHONE','HIVEMIND']);
  const short=(value,max)=>typeof value==='string'?value.replace(/\s+/g,' ').trim().slice(0,max):'';
  const level=value=>typeof value==='number'&&Number.isFinite(value)?Math.max(0,Math.min(100,value)):50;
  function make(config={}){
    if(config.mode!=='fiction')return{credits:'SOURCE HOLD // Credits skipped. Your words stay yours.',bloopers:'SOURCE HOLD // Blooper Reel skipped. No outtakes made from a held source.'};
    const cast=short(config.name,160)||'Unnamed fictional character',role=short(config.job,160);
    const active=Array.isArray(config.activeStages)?[...new Set(config.activeStages.filter(x=>typeof x==='string').map(x=>short(x,80)).filter(x=>x&&!['CREDITS','BLOOPER REEL'].includes(x)))].slice(0,16):[];
    const rows=['14 // CREDITS','FICTIONAL CAST // '+cast];
    if(role)rows.push('ROLE // '+role);
    rows.push('ORIGINAL INPUT // supplied by the person at the keyboard','STORY // generated by Bullshit Telephone World','SOUNDTRACK // make or edit it in Dot Studio');
    if(active.length)rows.push('MACHINE CREW // '+active.slice(0,3+Math.floor(level(config.creditsLevel)/8)).join(' → '));
    rows.push('THE END // Credits do not rewrite the ending or feed the hopper.');
    const clips=[],seen=new Set(),maxClips=1+Math.floor(level(config.bloopersLevel)*7/100),maxLength=160+Math.floor(level(config.bloopersLevel)*3.4);
    if(Array.isArray(config.clips))for(const item of config.clips.slice(0,80)){
      if(!item||!STAGES.has(item.stage)||typeof item.text!=='string')continue;
      const text=item.text.replace(/\s+/g,' ').trim();if(!text||seen.has(text)||/^\[.*BYPASSED.*\]$/.test(text))continue;
      seen.add(text);clips.push('TAKE '+String(clips.length+1).padStart(2,'0')+' // '+item.stage+'\n'+text.slice(0,maxLength)+(text.length>maxLength?'…':''));
      if(clips.length>=maxClips)break;
    }
    return{
      credits:config.creditsOn===false?'[ CREDITS BYPASSED ]':rows.join('\n\n'),
      bloopers:config.bloopersOn===false?'[ BLOOPER REEL BYPASSED ]':'15 // BLOOPER REEL\nACTUAL MACHINE TAKES // excerpts from this run, not alternate endings.\n\n'+(clips.length?clips.join('\n\n'):'No outtakes this run. The contributing stages were bypassed or produced no take.')+'\n\nCUT // The final story stays as it is.'
    };
  }
  const api=Object.freeze({make});
  if(typeof module!=='undefined'&&module.exports)module.exports=api;else root.TelephonePostRoll=api;
})(globalThis);
